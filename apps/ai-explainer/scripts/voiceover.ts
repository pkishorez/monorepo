// Usage: pnpm voiceover <explainer>
// Speaks each line of src/explainers/<explainer>/script.ts with the Foundation
// voice and writes compressed audio plus a typed voiceover.ts beside it.
// Lines whose text and voice are unchanged are kept as they are.
import { execFileSync } from 'node:child_process';
import {
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { join, resolve } from 'node:path';
import { KokoroTTS } from 'kokoro-js';
import { voice } from '../src/foundation/voice/index.ts';

type Line = {
  id: string;
  text: string;
  speaker: string;
  speed: number;
  seconds: number;
};

const name = process.argv[2];
if (!name) throw new Error('Usage: pnpm voiceover <explainer>');

const folder = resolve('src/explainers', name);
const audioFolder = join(folder, 'voiceover');
const manifestPath = join(audioFolder, 'voiceover.json');
const { script } = (await import(join(folder, 'script.ts'))) as {
  script: readonly { id: string; say: string }[];
};

mkdirSync(audioFolder, { recursive: true });
const previous: Line[] = existsSync(manifestPath)
  ? JSON.parse(readFileSync(manifestPath, 'utf8'))
  : [];

let tts: KokoroTTS | undefined;
const lines: Line[] = [];
for (const { id, say } of script) {
  const kept = previous.find(
    (line) =>
      line.id === id &&
      line.text === say &&
      line.speaker === voice.speaker &&
      line.speed === voice.speed &&
      existsSync(join(audioFolder, `${id}.mp3`)),
  );
  if (kept) {
    lines.push(kept);
    continue;
  }
  tts ??= await KokoroTTS.from_pretrained(voice.model, {
    dtype: 'q8',
    device: 'cpu',
  });
  const audio = await tts.generate(say, {
    voice: voice.speaker as never,
    speed: voice.speed,
  });
  const wav = join(audioFolder, `${id}.wav`);
  await audio.save(wav);
  execFileSync('ffmpeg', [
    '-y',
    '-loglevel',
    'error',
    '-i',
    wav,
    '-ac',
    '1',
    '-b:a',
    '64k',
    join(audioFolder, `${id}.mp3`),
  ]);
  rmSync(wav);
  const seconds = Number((audio.audio.length / audio.sampling_rate).toFixed(3));
  lines.push({
    id,
    text: say,
    speaker: voice.speaker,
    speed: voice.speed,
    seconds,
  });
  console.log(`spoke ${id} (${seconds}s)`);
}

writeFileSync(manifestPath, `${JSON.stringify(lines, null, 2)}\n`);
writeFileSync(
  join(folder, 'voiceover.ts'),
  `// Generated by \`pnpm voiceover ${name}\`. Do not edit.
import manifest from './voiceover/voiceover.json';
${lines.map((line, i) => `import line${i} from './voiceover/${line.id}.mp3';`).join('\n')}

const sources = [${lines.map((_, i) => `line${i}`).join(', ')}];

export const voiceover = {
  lines: manifest.map((line, i) => ({ ...line, src: sources[i]! })),
};
`,
);
console.log(
  `voiceover for ${name}: ${lines.reduce((sum, line) => sum + line.seconds, 0).toFixed(1)}s`,
);
