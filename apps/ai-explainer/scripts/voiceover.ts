// Usage: pnpm voiceover <name>
// Speaks each line of the script.ts of the Explainer or Walkthrough <name>
// with the Foundation voice and writes levelled, compressed audio plus a
// typed voiceover.ts beside it. Lines whose text and voice are unchanged are
// kept as they are.
import { execFileSync } from 'node:child_process';
import {
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { join, resolve } from 'node:path';
import { voice } from '../src/foundation/voice/index.ts';
import { speak } from './speak.ts';

type Line = {
  id: string;
  text: string;
  speaker: string;
  speed: number;
  seconds: number;
};

const name = process.argv[2];
if (!name) throw new Error('Usage: pnpm voiceover <name>');

const folder = ['src/explainers', 'src/walkthroughs']
  .map((parent) => resolve(parent, name))
  .find((candidate) => existsSync(join(candidate, 'script.ts')));
if (!folder) throw new Error(`No Explainer or Walkthrough "${name}"`);
const audioFolder = join(folder, 'voiceover');
const manifestPath = join(audioFolder, 'voiceover.json');
const { script } = (await import(join(folder, 'script.ts'))) as {
  script: readonly { id: string; say: string }[];
};

mkdirSync(audioFolder, { recursive: true });
const previous: Line[] = existsSync(manifestPath)
  ? JSON.parse(readFileSync(manifestPath, 'utf8'))
  : [];

const lines: Line[] = [];
for (const { id, say } of script) {
  const kept = previous.find(
    (line) =>
      line.id === id &&
      line.text === say &&
      line.speaker === voice.speaker &&
      line.speed === voice.speed &&
      existsSync(join(audioFolder, `${id}.mp3`)),
  );
  if (kept) {
    lines.push(kept);
    continue;
  }
  const wav = join(audioFolder, `${id}.wav`);
  await speak(say, wav);
  const seconds = Number(
    Number(
      execFileSync('ffprobe', [
        '-v',
        'error',
        '-show_entries',
        'format=duration',
        '-of',
        'csv=p=0',
        wav,
      ]),
    ).toFixed(3),
  );
  // Every line is levelled to the same loudness, so the mix under it holds.
  execFileSync('ffmpeg', [
    '-y',
    '-loglevel',
    'error',
    '-i',
    wav,
    '-af',
    'loudnorm=I=-18:TP=-2:LRA=11',
    '-ar',
    '24000',
    '-ac',
    '1',
    '-b:a',
    '64k',
    join(audioFolder, `${id}.mp3`),
  ]);
  rmSync(wav);
  lines.push({
    id,
    text: say,
    speaker: voice.speaker,
    speed: voice.speed,
    seconds,
  });
  console.log(`spoke ${id} (${seconds}s)`);
}

writeFileSync(manifestPath, `${JSON.stringify(lines, null, 2)}\n`);
writeFileSync(
  join(folder, 'voiceover.ts'),
  `// Generated by \`pnpm voiceover ${name}\`. Do not edit.
import manifest from './voiceover/voiceover.json';
${lines.map((line, i) => `import line${i} from './voiceover/${line.id}.mp3';`).join('\n')}

const sources = [${lines.map((_, i) => `line${i}`).join(', ')}];

export const voiceover = {
  lines: manifest.map((line, i) => ({ ...line, src: sources[i]! })),
};
`,
);
console.log(
  `voiceover for ${name}: ${lines.reduce((sum, line) => sum + line.seconds, 0).toFixed(1)}s`,
);
